const module = "github.com/yangtao121/workos"

func TestDomainPackagesStayInfrastructureFree(t *testing.T) {
	t.Parallel()
	banned := []string{
		"connectrpc.com/", "database/sql", "github.com/jackc/pgx/", "net/http", "os", "os/exec",
		module + "/gen/", module + "/internal/platform/", "/adapters/", "/transport/",
	}
	walkGo(t, filepath.Join(repoRoot(), "internal"), func(path, importPath string) {
		if !pathSegment(path, "domain") {
			return
		}
		for _, value := range banned {
			if importPath == value || strings.HasPrefix(importPath, value) || strings.Contains(importPath, value) {
				t.Errorf("domain boundary: %s imports %q", relative(path), importPath)
			}
		}
	})
}

func TestProcessInternalsDoNotCrossImport(t *testing.T) {
	t.Parallel()
	processes := []string{"core", "gateway", "harness", "runtime", "reliability", "indexer"}
	root := repoRoot()
	for _, owner := range processes {
		owner := owner
		base := filepath.Join(root, "internal", owner)
		if _, err := os.Stat(base); err != nil {
			if os.IsNotExist(err) {
				continue
			}
			t.Fatal(err)
		}
		walkGo(t, base, func(path, importPath string) {
			for _, other := range processes {
				if other == owner {
					continue
				}
				if strings.HasPrefix(importPath, module+"/internal/"+other) {
					t.Errorf("process boundary: %s imports %q", relative(path), importPath)
				}
			}
		})
	}
}

func TestGeneratedSourcesKeepGeneratorMarkers(t *testing.T) {
	t.Parallel()
	checks := map[string]string{
		"gen/go":               "Code generated by",
		"sdk/protocol/src/gen": "@generated by protoc-gen-es",
		"internal/core/project/adapters/postgres/projectdb":    "Code generated by sqlc",
		"internal/core/agent/adapters/postgres/agentdb":        "Code generated by sqlc",
		"internal/core/appregistry/adapters/postgres/appdb":    "Code generated by sqlc",
		"internal/core/artifact/adapters/postgres/artifactdb":  "Code generated by sqlc",
		"internal/runtime/surface/adapters/postgres/surfacedb": "Code generated by sqlc",
	}
	for directory, marker := range checks {
		directory, marker := directory, marker
		err := filepath.WalkDir(filepath.Join(repoRoot(), directory), func(path string, entry fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if entry.IsDir() || (!strings.HasSuffix(path, ".go") && !strings.HasSuffix(path, ".ts")) {
				return nil
			}
			file, err := os.Open(path)
			if err != nil {
				return err
			}
			defer file.Close()
			scanner := bufio.NewScanner(file)
			for line := 0; line < 8 && scanner.Scan(); line++ {
				if strings.Contains(scanner.Text(), marker) {
					return nil
				}
			}
			t.Errorf("generated-source boundary: %s is missing %q", relative(path), marker)
			return scanner.Err()
		})
		if err != nil {
			t.Fatalf("scan %s: %v", directory, err)
		}
	}
}

func TestCorePostgresAdaptersDoNotQueryOtherModuleTables(t *testing.T) {
	t.Parallel()
	checks := []struct {
		path      string
		forbidden string
	}{
		{path: "internal/core/agent/adapters/postgres/queries.sql", forbidden: "workos_core.projects"},
		{path: "internal/core/project/adapters/postgres/queries.sql", forbidden: "workos_core.agent_tasks"},
		{path: "internal/core/project/adapters/postgres/queries.sql", forbidden: "workos_core.app_versions"},
		{path: "internal/core/appregistry/adapters/postgres/queries.sql", forbidden: "workos_core.projects"},
		{path: "internal/core/appregistry/adapters/postgres/queries.sql", forbidden: "workos_core.project_app_installations"},
		{path: "internal/core/artifact/adapters/postgres/queries.sql", forbidden: "workos_core.projects"},
		{path: "internal/core/artifact/adapters/postgres/queries.sql", forbidden: "workos_core.app_versions"},
		{path: "internal/core/artifact/adapters/postgres/queries.sql", forbidden: "workos_core.project_app_installations"},
		{path: "internal/runtime/surface/adapters/postgres/queries.sql", forbidden: "workos_core."},
	}
	for _, check := range checks {
		data, err := os.ReadFile(filepath.Join(repoRoot(), check.path))
		if err != nil {
			t.Fatal(err)
		}
		if strings.Contains(strings.ToLower(string(data)), check.forbidden) {
			t.Errorf("module SQL boundary: %s references %s", check.path, check.forbidden)
		}
	}
}

func walkGo(t *testing.T, root string, visit func(path, importPath string)) {
	t.Helper()
	err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || !strings.HasSuffix(path, ".go") {
			return nil
		}
		file, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.ImportsOnly)
		if err != nil {
			return fmt.Errorf("parse %s: %w", path, err)
		}
		for _, imported := range file.Imports {
			value, err := strconv.Unquote(imported.Path.Value)
			if err != nil {
				return err
			}
			visit(path, value)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
}

func pathSegment(path, segment string) bool {
	parts := strings.Split(filepath.ToSlash(path), "/")
	return slices.Contains(parts, segment)
}

func repoRoot() string {
	_, source, _, _ := runtime.Caller(0)
	return filepath.Clean(filepath.Join(filepath.Dir(source), "..", ".."))
}

func relative(path string) string {
	value, err := filepath.Rel(repoRoot(), path)
	if err != nil {
		return path
	}
	return filepath.ToSlash(value)
}
